// Search has to find "подарок" typed as "подар" and also cope with someone
// pasting the emoji itself.
function searchEmojis(query, limit = 120) {
  const needle = String(query || "").trim().toLowerCase();
  if (!needle) {
    return [];
  }
  const found = [];
  const seen = new Set();
  for (const category of CATEGORIES) {
    for (const [emoji, keywords] of category.emojis) {
      if (seen.has(emoji)) continue;
      const haystack = `${keywords} ${category.label.toLowerCase()}`;
      const hit =
        emoji === needle ||
        haystack.split(/\s+/).some((word) => word.startsWith(needle)) ||
        haystack.includes(needle);
      if (hit) {
        seen.add(emoji);
        found.push(emoji);
        if (found.length >= limit) return found;
      }
    }
  }
  return found;
}

function allEmojis() {
  const seen = new Set();
  for (const category of CATEGORIES) {
    for (const [emoji] of category.emojis) {
      seen.add(emoji);
    }
  }
  return [...seen];
}

module.exports = { CATEGORIES, searchEmojis, allEmojis };
